from __future__ import annotations

import bisect
import json
import os
import re
import subprocess
import sys
from dataclasses import dataclass, field

try:
    import tomllib
except ImportError:
    import tomli as tomllib

from mozlint import result
from mozlint.pathutils import expand_exclusions

CLIPPY_FIX_ARGS = ("--fix", "--allow-no-vcs")
# `cargo metadata` output for the whole workspace, generated by the build for
# cbindgen and regenerated when Cargo.toml / Cargo.lock change.
OBJDIR_METADATA = "config/cargo-metadata.json"
# `cargo fix` reports what it changed as e.g. `Fixed foo/bar.rs (3 fixes)`.
FIXED_RE = re.compile(r"^\s*Fixed .* \((\d+) fix(?:es)?\)$")


def get_clippy_driver_flags(config):
    """Build clippy driver flags (-W/-A/-D) from the warn/allow/deny lists in
    clippy.yml. Order matters: warns (often lint groups) come first, then the
    allows that opt back out of individual lints from those groups, then the
    denys. For a given lint the rightmost flag wins."""
    flags = []
    for lint in config.get("warn", []):
        flags.extend(["-W", f"clippy::{lint}"])
    for lint in config.get("allow", []):
        flags.extend(["-A", f"clippy::{lint}"])
    for lint in config.get("deny", []):
        flags.extend(["-D", f"clippy::{lint}"])
    return flags


def in_sorted_list(l, x):
    i = bisect.bisect_left(l, x)
    return i < len(l) and l[i] == x


def handle_clippy_msg(config, line, log, base_path, files, lint_results):
    try:
        detail = json.loads(line)
        if "message" in detail:
            p = detail["target"]["src_path"]
            detail = detail["message"]
            if "level" in detail:
                if (detail["level"] in {"error", "failure-note"}) and not detail[
                    "code"
                ]:
                    log.debug(
                        "Error outside of clippy."
                        "This means that the build failed. Therefore, skipping this"
                    )
                    log.debug(f"File = {p} / Detail = {detail}")
                    return
                # We are in a clippy warning
                if len(detail["spans"]) == 0:
                    # For some reason, at the end of the summary, we can
                    # get the following line
                    # {'rendered': 'warning: 5 warnings emitted\n\n', 'children':
                    # [], 'code': None, 'level': 'warning', 'message':
                    # '5 warnings emitted', 'spans': []}
                    # if this is the case, skip it
                    log.debug(f"Skipping the summary line {detail} for file {p}")
                    return

                l = detail["spans"][0]
                p = os.path.join(base_path, l["file_name"])
                # Dependencies of the requested crates get linted too, and
                # some warnings point into generated code in the objdir.
                if files and not in_sorted_list(files, p):
                    return
                line = l["line_start"]
                res = {
                    "path": p,
                    "level": detail["level"],
                    "lineno": line,
                    "column": l["column_start"],
                    "message": detail["message"],
                    "hint": detail["rendered"],
                    "rule": detail["code"]["code"],
                    "lineoffset": l["line_end"] - l["line_start"],
                }
                log.debug(f"Identified an issue in {p}:{line}")
                lint_results["results"].append(result.from_config(config, **res))

    except json.decoder.JSONDecodeError:
        # Could not parse the message.
        # It is usually cargo info like "Finished `release` profile", etc
        return


def count_fixes(stdout):
    return sum(int(m.group(1)) for m in map(FIXED_RE.match, stdout.splitlines()) if m)


def crate_name_for_path(path, root, cache):
    """Return the name of the crate whose Cargo.toml is closest above `path`
    (stopping at `root`), or None if there is none."""
    directory = path if os.path.isdir(path) else os.path.dirname(path)
    root = os.path.normpath(root)
    visited = []
    name = None
    while True:
        directory = os.path.normpath(directory)
        if directory in cache:
            name = cache[directory]
            break
        visited.append(directory)
        manifest = os.path.join(directory, "Cargo.toml")
        if os.path.isfile(manifest):
            try:
                with open(manifest, "rb") as fh:
                    name = tomllib.load(fh).get("package", {}).get("name")
            except (OSError, tomllib.TOMLDecodeError):
                name = None
            if name:
                break
        parent = os.path.dirname(directory)
        if directory in (root, parent):
            break
        directory = parent
    for directory in visited:
        cache[directory] = name
    return name


def crates_for_paths(paths, root, log):
    cache = {}
    crates = set()
    for path in paths:
        name = crate_name_for_path(path, root, cache)
        if name is None:
            log.debug(f"{path} is not part of any crate, skipping")
        else:
            crates.add(name)
    return sorted(crates)


def gkrust_graph_crates(root, topobjdir, log):
    """Names of every package in the gkrust workspace dependency graph, read
    from the metadata the build generates in the objdir."""
    if not topobjdir:
        raise RuntimeError(
            "The clippy linter needs an objdir with an existing build; run "
            "./mach build first"
        )
    metadata = os.path.join(topobjdir, OBJDIR_METADATA)
    try:
        with open(metadata) as fh:
            data = json.load(fh)
        # Unused `[patch]` entries are listed as packages but aren't part of the
        # dependency graph, and cargo rejects selecting them.
        in_graph = {node["id"] for node in data["resolve"]["nodes"]}
        packages = [pkg for pkg in data["packages"] if pkg["id"] in in_graph]
    except (OSError, ValueError, KeyError, TypeError) as e:
        raise RuntimeError(
            f"Couldn't read the cargo metadata in {metadata} ({e}); run "
            "./mach build first"
        )
    lockfile = os.path.join(root, "Cargo.lock")
    if os.path.isfile(lockfile) and os.path.getmtime(metadata) < os.path.getmtime(
        lockfile
    ):
        log.warning(
            f"{metadata} is older than {lockfile}; run ./mach build to refresh it"
        )
    return {pkg["name"] for pkg in packages}


def check_clippy_ran(completed_proc, crate_name, log):
    """Raise if clippy failed to execute (e.g. build environment not set up).

    `mach cargo` doesn't propagate cargo's exit code, but cargo always emits at
    least a `build-finished` message when it runs, so also treat the absence of
    any JSON as a failure."""

    def is_valid_json(line):
        try:
            json.loads(line)
            return True
        except json.JSONDecodeError:
            return False

    has_cargo_json = any(
        is_valid_json(line) for line in completed_proc.stdout.splitlines()
    )
    if not has_cargo_json:
        output = completed_proc.stderr.strip() or completed_proc.stdout.strip()
        log.error(
            "clippy failed to execute for crate '%s' (exit code %d):\n%s",
            crate_name,
            completed_proc.returncode,
            output,
        )
        raise RuntimeError(
            f"Failed to run clippy on '{crate_name}' "
            f"(exit code {completed_proc.returncode}). "
            "Ensure the build environment is set up correctly."
        )


def group_paths(paths, config, root):
    """
    Groups input paths based on the crate we need to check

    returns: List of (crate_name, paths) tuples
    """
    gkrust_path_group = PathGroup("gkrust", root)
    non_gkrust_path_groups = []
    non_gkrust_crates = config.get("non_gkrust_crates", {})
    for crate_name, crate_root in non_gkrust_crates.items():
        non_gkrust_path_groups.append(
            PathGroup(crate_name, os.path.join(root, crate_root))
        )

    for path in paths:
        path_group = gkrust_path_group
        for candidate in non_gkrust_path_groups:
            if path.startswith(candidate.crate_root):
                path_group = candidate
                break
        path_group.paths.append(path)
    return [p for p in [gkrust_path_group] + non_gkrust_path_groups if p.paths]


@dataclass
class PathGroup:
    """
    Tracks paths to lint based on the Rust crate we're running clippy on.
    """

    crate_name: str
    crate_root: str
    paths: list[str] = field(default_factory=list)


def lint(paths, config, log, root, substs=None, topobjdir=None, fix=None, **_lintargs):
    if substs is None:
        substs = {}
    lint_results = {
        "results": [],
        "fixed": 0,
    }

    cargo_bin = substs.get("CARGO", "cargo")

    errors = []
    for path_group in group_paths(paths, config, root):
        try:
            if path_group.crate_name == "gkrust":
                lint_gkrust(path_group, config, log, fix, root, topobjdir, lint_results)
            else:
                lint_crate(path_group, config, log, fix, root, cargo_bin, lint_results)
        except RuntimeError as e:
            errors.append(str(e))

    if errors:
        raise RuntimeError("\n".join(errors))

    # Cargo may check a crate several times (e.g. host and target builds, or
    # different feature sets), which would repeat every warning in it.
    seen = set()
    unique = []
    for res in lint_results["results"]:
        key = (res.path, res.lineno, res.column, res.rule, res.message)
        if key not in seen:
            seen.add(key)
            unique.append(res)
    lint_results["results"] = unique
    return lint_results


def lint_gkrust(path_group, config, log, fix, root, topobjdir, lint_results):
    """
    Lint crates that are part of the gkrust workspace.

    Only the crates the given paths belong to are passed to cargo (via `-p`),
    rather than the whole workspace. That keeps the amount of code cargo has to
    re-check small, and it's also what makes `--fix` work: `cargo fix` only
    rewrites the packages selected on the command line, and gkrust itself has
    next to no code of its own. Dependencies of the selected crates still get
    linted, so results are filtered down to the requested paths afterwards.
    """
    paths = list(expand_exclusions(path_group.paths, config, root))
    paths.sort()
    crates = crates_for_paths(paths, root, log)
    if not crates:
        log.debug("No gkrust workspace crates to lint")
        return
    known_crates = gkrust_graph_crates(root, topobjdir, log)
    for crate in crates:
        if crate not in known_crates:
            log.warning(
                f"{crate} is not in the gkrust dependency graph according to "
                f"{OBJDIR_METADATA}, skipping it"
            )
    crates = [crate for crate in crates if crate in known_crates]
    if not crates:
        log.debug("No gkrust workspace crates to lint")
        return

    # gkrust depends on things from the mach environment, so we need to run `./mach cargo` instead
    # of `cargo` directly.
    mach_path = root + "/mach"
    # can be extended in build/cargo/cargo-clippy.yaml
    clippy_args = [
        sys.executable,
        mach_path,
        "--log-no-times",
        "cargo",
        "clippy",
    ]
    for crate in crates:
        clippy_args.extend(["-p", crate])
    if fix:
        clippy_args.extend(CLIPPY_FIX_ARGS)
    # --keep-going lets cargo check independent crates even after one fails,
    # so a single broken crate doesn't hide warnings in everything downstream.
    clippy_args.extend(["--", "--keep-going", "--message-format=json"])
    driver_flags = get_clippy_driver_flags(config)
    # MOZ_RUST_DEFAULT_FLAGS sets `-Dwarnings` (warnings-as-errors), which
    # promotes any clippy warning to a hard error and stops cargo at the first
    # offending crate. For linting we want to surface every warning across
    # every included crate, so demote it back to warn-level (last `-W/-D` wins
    # for the same lint group, and extra_rustflags is appended after the
    # defaults).
    flags = ["-W", "warnings"] + driver_flags
    env = os.environ.copy()
    env["extra_rustflags"] = " ".join(flags)
    log.debug("Run clippy with = {}".format(" ".join(clippy_args)))
    completed_proc = subprocess.run(
        clippy_args,
        check=False,  # non-zero exit codes are not unexpected
        capture_output=True,
        text=True,
        env=env,
    )
    check_clippy_ran(completed_proc, ", ".join(crates), log)
    for l in completed_proc.stdout.splitlines():
        handle_clippy_msg(config, l, log, root, paths, lint_results)

    if fix:
        lint_results["fixed"] += count_fixes(completed_proc.stdout)


def lint_crate(path_group, config, log, fix, root, cargo_bin, lint_results):
    """
    Lint crates other than gkrust.

    These are newer and more self-contained, so we can use a more aggressive approach to linting:
      * Print out all clippy errors for the crate.
      * Support the `--fix` flag to automatically apply fixes.
    """
    clippy_args = [
        cargo_bin,
        "clippy",
        "-p",
        path_group.crate_name,
        "--message-format=json",
    ]
    if fix:
        clippy_args.extend([*CLIPPY_FIX_ARGS, "--allow-dirty"])
    driver_flags = get_clippy_driver_flags(config)
    if driver_flags:
        clippy_args.extend(["--"] + driver_flags)
    log.debug("Run clippy with = {}".format(" ".join(clippy_args)))
    completed_proc = subprocess.run(
        clippy_args,
        check=False,  # non-zero exit codes are not unexpected
        capture_output=True,
        text=True,
    )
    check_clippy_ran(completed_proc, path_group.crate_name, log)

    for l in completed_proc.stdout.splitlines():
        handle_clippy_msg(config, l, log, root, None, lint_results)

    if fix:
        lint_results["fixed"] += count_fixes(
            completed_proc.stdout + completed_proc.stderr
        )
